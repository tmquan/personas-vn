def render_dataexploration() -> None:
    curator_dir = REPO_ROOT / "data" / "nso-gov-vn"
    extracted_path = curator_dir / "extracted" / "extracted.jsonl"
    embedded_path = curator_dir / "embedded" / "embedded.parquet"
    reduced_path = curator_dir / "reduced" / "reduced.parquet"
    for p in (extracted_path, embedded_path, reduced_path):
        if not p.exists():
            print(f"  SKIP DATAEXPLORATION — {p} missing; run DATAEXPLORATION.ipynb first")
            return

    extracted = pd.read_json(extracted_path, lines=True)
    embedded = pd.read_parquet(embedded_path)
    reduced = pd.read_parquet(reduced_path)

    # Mirrors §6 — sc = reduced ⨝ extracted on id, with helper fields.
    sc = reduced.merge(
        extracted[["id", "database", "n_cells", "year_min", "year_max", "keywords"]],
        on="id",
        how="left",
    )
    sc["domain_id"] = sc["domain_id"].fillna("other")
    sc["kw_str"] = sc["keywords"].apply(
        lambda kw: ", ".join(kw[:5]) if isinstance(kw, list) else ""
    )

    DOMAIN_PALETTE = [
        NV_GREEN,
        NV_GREEN_DARK,
        NV_GREEN_SOFT,
        NV_BLACK,
        NV_GREY,
        "#3F6F00",
        "#94BD51",
        "#AED581",
        "#5C9300",
        NV_DARK,
        "#888888",
        "#444444",
    ]

    # ------- fig06 — UMAP × statistical domain -------
    fig06 = go.Figure()
    domain_order = sc["domain_id"].value_counts().index.tolist()
    for dom, color in zip(domain_order, DOMAIN_PALETTE):
        sub = sc[sc["domain_id"] == dom]
        fig06.add_trace(
            go.Scatter(
                x=sub["x"],
                y=sub["y"],
                mode="markers",
                name=_wrap(DOMAIN_VI_EN.get(dom, dom)),
                marker=dict(
                    size=8,
                    color=color,
                    line=dict(color=NV_BLACK, width=0.4),
                    opacity=0.85,
                ),
                customdata=np.column_stack(
                    [
                        sub["title"].fillna(""),
                        sub["database"].fillna(""),
                        sub["n_cells"].fillna(0).astype(int),
                        sub["kw_str"].fillna(""),
                    ]
                ),
                hovertemplate=(
                    "<b>%{customdata[0]}</b><br>"
                    "database: %{customdata[1]}<br>"
                    "cells: %{customdata[2]:,}<br>"
                    "keywords: %{customdata[3]}<extra></extra>"
                ),
            )
        )
    fig06.update_layout(
        title="UMAP — 502 bảng PX-Web tô màu theo lĩnh vực / "
        "UMAP — 502 PX-Web tables coloured by ontology domain",
        xaxis_title="UMAP-1",
        yaxis_title="UMAP-2",
    )
    apply_nvidia_style(fig06)
    fig06.update_layout(
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        margin=EMBED_MARGIN_CATEGORICAL,
        legend=EMBED_LEGEND_RIGHT,
    )
    save_figure(
        fig06,
        "06_umap_by_domain",
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        out_dir=EXPL_OUT,
    )
    print("  wrote docs/figures/exploration/06_umap_by_domain.png")

    # ------- fig07 — UMAP × NSO database (raw data column, not cluster) -------
    fig07 = go.Figure()
    DB_PALETTE = DOMAIN_PALETTE  # same 12-colour palette
    db_order = sc["database"].fillna("(unknown)").value_counts().index.tolist()
    for db, color in zip(db_order, DB_PALETTE):
        sub = sc[sc["database"].fillna("(unknown)") == db]
        fig07.add_trace(
            go.Scatter(
                x=sub["x"],
                y=sub["y"],
                mode="markers",
                name=_wrap(str(db)),
                marker=dict(
                    size=8,
                    color=color,
                    line=dict(color=NV_BLACK, width=0.4),
                    opacity=0.85,
                ),
                customdata=np.column_stack(
                    [
                        sub["title"].fillna(""),
                        sub["domain_id"].fillna(""),
                        sub["kw_str"].fillna(""),
                    ]
                ),
                hovertemplate=(
                    "<b>%{customdata[0]}</b><br>"
                    "domain: %{customdata[1]}<br>"
                    "keywords: %{customdata[2]}<extra></extra>"
                ),
            )
        )
    fig07.update_layout(
        title="UMAP — 502 bảng PX-Web tô màu theo cơ sở dữ liệu NSO / "
        "UMAP — 502 PX-Web tables coloured by NSO database",
        xaxis_title="UMAP-1",
        yaxis_title="UMAP-2",
    )
    apply_nvidia_style(fig07)
    fig07.update_layout(
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        margin=EMBED_MARGIN_CATEGORICAL,
        legend=EMBED_LEGEND_RIGHT,
    )
    save_figure(
        fig07,
        "07_umap_by_database",
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        out_dir=EXPL_OUT,
    )
    print("  wrote docs/figures/exploration/07_umap_by_database.png")

    # ------- fig08 — UMAP × cell count (continuous) -------
    sc["log_n"] = np.log10(sc["n_cells"].fillna(1).clip(lower=1))
    fig08 = go.Figure(
        go.Scatter(
            x=sc["x"],
            y=sc["y"],
            mode="markers",
            marker=dict(
                size=8,
                color=sc["log_n"],
                colorscale=NV_SEQUENTIAL,
                line=dict(color=NV_BLACK, width=0.4),
                opacity=0.9,
                showscale=True,
                colorbar=dict(
                    title=dict(
                        text="log₁₀(cells)",
                        font=dict(family=NV_FONT_FAMILY, color=NV_BLACK, size=12),
                    ),
                    tickvals=[0, 1, 2, 3, 4],
                    ticktext=["1", "10", "100", "1k", "10k"],
                ),
            ),
            customdata=np.column_stack(
                [
                    sc["title"].fillna(""),
                    sc["domain_id"].fillna(""),
                    sc["n_cells"].fillna(0).astype(int),
                ]
            ),
            hovertemplate=(
                "<b>%{customdata[0]}</b><br>"
                "domain: %{customdata[1]}<br>"
                "cells: %{customdata[2]:,}<extra></extra>"
            ),
        )
    )
    fig08.update_layout(
        title="UMAP × kích thước bảng / UMAP × table size (log₁₀ cells)",
        xaxis_title="UMAP-1",
        yaxis_title="UMAP-2",
        showlegend=False,
    )
    apply_nvidia_style(fig08)
    fig08.update_layout(
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        margin=EMBED_MARGIN_CONTINUOUS,
    )
    save_figure(
        fig08,
        "08_umap_by_cellcount",
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        out_dir=EXPL_OUT,
    )
    print("  wrote docs/figures/exploration/08_umap_by_cellcount.png")

    # ------- fig09 — UMAP × recency (continuous + small categorical) -------
    ymax = sc["year_max"].fillna(0)
    no_year = ymax == 0
    fig09 = go.Figure()
    sub = sc[no_year]
    fig09.add_trace(
        go.Scatter(
            x=sub["x"],
            y=sub["y"],
            mode="markers",
            name="no year info",
            marker=dict(
                size=7,
                color=NV_LIGHT_GREY,
                line=dict(color=NV_GREY, width=0.4),
                opacity=0.7,
            ),
            hovertemplate="<b>%{customdata[0]}</b><br>(no year info)<extra></extra>",
            customdata=np.column_stack([sub["title"].fillna("")]),
        )
    )
    sub = sc[~no_year]
    fig09.add_trace(
        go.Scatter(
            x=sub["x"],
            y=sub["y"],
            mode="markers",
            name="by year_max",
            marker=dict(
                size=8,
                color=sub["year_max"],
                colorscale=NV_SEQUENTIAL,
                cmin=2010,
                cmax=2024,
                line=dict(color=NV_BLACK, width=0.4),
                opacity=0.9,
                showscale=True,
                colorbar=dict(
                    title=dict(
                        text="year_max",
                        font=dict(family=NV_FONT_FAMILY, color=NV_BLACK, size=12),
                    ),
                ),
            ),
            customdata=np.column_stack(
                [
                    sub["title"].fillna(""),
                    sub["year_min"].fillna(0).astype(int),
                    sub["year_max"].fillna(0).astype(int),
                ]
            ),
            hovertemplate=(
                "<b>%{customdata[0]}</b><br>"
                "%{customdata[1]} – %{customdata[2]}<extra></extra>"
            ),
        )
    )
    fig09.update_layout(
        title="UMAP × năm cập nhật mới nhất / UMAP × most-recent year",
        xaxis_title="UMAP-1",
        yaxis_title="UMAP-2",
    )
    apply_nvidia_style(fig09)
    fig09.update_layout(
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        margin=EMBED_MARGIN_CONTINUOUS,
        legend=dict(
            title="",
            orientation="h",
            yanchor="top",
            y=1.02,
            xanchor="left",
            x=0.0,
            font=dict(size=11),
            itemsizing="constant",
            bgcolor="rgba(255,255,255,0.85)",
        ),
    )
    save_figure(
        fig09,
        "09_umap_by_recency",
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        out_dir=EXPL_OUT,
    )
    print("  wrote docs/figures/exploration/09_umap_by_recency.png")

    # ------- fig11 — semantic neighbours -------
    emb_df = embedded.merge(
        extracted[["id", "database"]], on="id", how="left"
    )
    V = np.stack(emb_df["vector"].to_list())
    S = V @ V.T

    fig11 = go.Figure()
    fig11.add_trace(
        go.Scatter(
            x=sc["x"],
            y=sc["y"],
            mode="markers",
            name="all 502 tables",
            marker=dict(size=5, color=NV_LIGHT_GREY, opacity=0.5),
            hoverinfo="skip",
            showlegend=True,
        )
    )
    ANCHOR_TABLE_IDS = ["V02.01", "V03.01", "V07.01", "V14.45"]
    ANCHOR_PALETTE = [NV_GREEN, NV_GREEN_DARK, NV_BLACK, NV_DARK]
    for anchor_id, color in zip(ANCHOR_TABLE_IDS, ANCHOR_PALETTE):
        rows = emb_df[emb_df["id"].str.endswith(":" + anchor_id)]
        if rows.empty:
            continue
        i = rows.index[0]
        sim = S[i].copy()
        sim[i] = -np.inf
        top = np.argsort(sim)[::-1][:5]
        indices = [i] + list(top)
        sub = sc[sc["id"].isin(emb_df.loc[indices, "id"])]
        is_anchor = sub["id"] == emb_df.loc[i, "id"]
        fig11.add_trace(
            go.Scatter(
                x=sub["x"],
                y=sub["y"],
                mode="markers+text",
                name=f"{anchor_id} + 5 neighbours",
                text=[anchor_id if a else "" for a in is_anchor],
                textposition="top center",
                textfont=dict(color=NV_BLACK, size=12),
                marker=dict(
                    size=[14 if a else 9 for a in is_anchor],
                    color=color,
                    line=dict(color=NV_BLACK, width=1.0),
                    symbol=["star" if a else "circle" for a in is_anchor],
                ),
                customdata=np.column_stack(
                    [sub["title"].fillna(""), sub["domain_id"].fillna("")]
                ),
                hovertemplate="<b>%{customdata[0]}</b><br>%{customdata[1]}<extra></extra>",
            )
        )
    fig11.update_layout(
        title="Bốn cụm láng giềng ngữ nghĩa trên UMAP / "
        "Four semantic neighbour groups projected onto UMAP",
        xaxis_title="UMAP-1",
        yaxis_title="UMAP-2",
    )
    apply_nvidia_style(fig11)
    fig11.update_layout(
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        margin=EMBED_MARGIN_CATEGORICAL,
        legend=EMBED_LEGEND_RIGHT,
    )
    save_figure(
        fig11,
        "11_semantic_neighbours",
        width=EMBED_FIG_W,
        height=EMBED_FIG_H,
        out_dir=EXPL_OUT,
    )
    print("  wrote docs/figures/exploration/11_semantic_neighbours.png")


def main() -> None:
    print("DATASYNTHESIS — re-rendering figs 02..05 to docs/figures/synthesis/ ...")
    render_datasynthesis()
    print()
    print("DATAEXPLORATION — re-rendering figs 06..09, 11 to docs/figures/exploration/ ...")
    render_dataexploration()
    print()
    print("done.")


if __name__ == "__main__":
    main()
