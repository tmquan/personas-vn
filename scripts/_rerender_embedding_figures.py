# ---------------------------------------------------------------------------
# Standardised dimensions (kept in lockstep with the notebook builders)
# ---------------------------------------------------------------------------
EMBED_FIG_W = 1100
EMBED_FIG_H = 720
# Categorical layout reserves a 240-px right-side strip for the legend
# (mirrors the colorbar-right convention of the continuous figures);
# wrapped 30-char labels stack in a single tidy column.
EMBED_MARGIN_CATEGORICAL = dict(l=80, r=240, t=80, b=80)
EMBED_MARGIN_CONTINUOUS = dict(l=80, r=140, t=80, b=80)
WRAP_AT = 30


def _wrap(label, max_chars: int = WRAP_AT) -> str:
    """Word-aware <br> insertion so a long category label wraps onto
    multiple legend lines without ever splitting a token."""
    if not isinstance(label, str) or len(label) <= max_chars:
        return str(label)
    out, cur = [], ""
    for w in label.split():
        if cur and len(cur) + 1 + len(w) > max_chars:
            out.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        out.append(cur)
    return "<br>".join(out)


EMBED_LEGEND_RIGHT = dict(
    title="",
    orientation="v",
    yanchor="top",
    y=1,
    xanchor="left",
    x=1.02,
    font=dict(size=11),
    tracegroupgap=4,
    itemsizing="constant",
)


