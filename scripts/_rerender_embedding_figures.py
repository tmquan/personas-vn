"""Re-render every UMAP / embedding figure in DATASYNTHESIS.ipynb +
DATAEXPLORATION.ipynb with the standardised canvas, margins, and
multi-line legend treatment.

Why this exists separately from the notebook builders:
    `scripts._build_datasynthesis_nb` / `scripts._build_dataexploration_nb`
build the **notebook source** — they emit a fresh ``DATA*.ipynb`` whose
cells contain the new styling code, but they don't actually execute the
cells. The figures the markdown documents embed live as PNG / HTML files
under ``docs/figures/synthesis/`` and ``docs/figures/exploration/`` and
can only be regenerated by running the cells against real data. The
slowest cells (sentence-transformers embedding + UMAP) take ~10 min on
CPU and we don't want to pay that cost just to restyle the 9 scatter
plots — the cached parquets they wrote (``reduced.parquet`` and friends)
already carry every input the figures need.

This script reads those cached parquets directly and re-renders the 9
embedding figures (4 from DATASYNTHESIS — figs 02-05; 5 from
DATAEXPLORATION — figs 06, 07, 08, 09, 11) with the same standardised
``EMBED_FIG_W`` × ``EMBED_FIG_H`` canvas, ``EMBED_MARGIN_*`` margins,
and ``_wrap``-driven multi-line legend that the notebook builders now
emit. Outputs land in the same ``docs/figures/{synthesis,exploration}/``
locations the notebooks use, so ``DATA*.md`` keeps rendering correctly
without any re-execution.

Run::

    python -m scripts._rerender_embedding_figures
"""

