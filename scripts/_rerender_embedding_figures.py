# DATASYNTHESIS — fig 02..05 from data/Nemotron-Personas-Vietnam/_subset_pipeline
# ---------------------------------------------------------------------------
def render_datasynthesis() -> None:
    subset_dir = REPO_ROOT / "data" / "Nemotron-Personas-Vietnam" / "_subset_pipeline"
    reduced_path = subset_dir / "reduced.parquet"
    if not reduced_path.exists():
        print(f"  SKIP DATASYNTHESIS — {reduced_path} missing; run DATASYNTHESIS.ipynb first")
        return

    reduced = pd.read_parquet(reduced_path)
    plot_sample = min(6000, len(reduced))

    def _scatter(color_col: str, title: str) -> go.Figure:
        df_plot = reduced.sample(plot_sample, random_state=20260506).copy()
        df_plot["_legend"] = df_plot[color_col].map(_wrap)
        legend_order = sorted(df_plot["_legend"].unique())
        fig = px.scatter(
            df_plot,
            x="x",
            y="y",
            color="_legend",
            title=title,
            opacity=0.7,
            color_discrete_sequence=NV_DISCRETE,
            category_orders={"_legend": legend_order},
            hover_data={
                "occupation": True,
                "region": True,
                "education_level": True,
                "_legend": False,
                "x": False,
                "y": False,
            },
        )
        fig.update_traces(marker=dict(size=4, line=dict(width=0)))
        fig.update_xaxes(title="UMAP-x")
        fig.update_yaxes(title="UMAP-y")
        apply_nvidia_style(fig)
        fig.update_layout(
            width=EMBED_FIG_W,
            height=EMBED_FIG_H,
            margin=EMBED_MARGIN_CATEGORICAL,
            legend=EMBED_LEGEND_RIGHT,
        )
        return fig

    targets = [
        ("region", "UMAP — coloured by macro-region", "02_umap_by_region"),
        (
            "occupation",
            "UMAP — coloured by occupation (10-class ISCO)",
            "03_umap_by_occupation",
        ),
        (
            "education_level",
            "UMAP — coloured by education level",
            "04_umap_by_education",
        ),
        (
            "area",
            "UMAP — coloured by area (urban / rural)",
            "05_umap_by_area",
        ),
    ]
    for col, title, name in targets:
        fig = _scatter(col, title)
        png, html = save_figure(
            fig,
            name,
            width=EMBED_FIG_W,
            height=EMBED_FIG_H,
            out_dir=SYNTH_OUT,
        )
        print(f"  wrote {png.relative_to(REPO_ROOT) if png else '(no png)'}")


